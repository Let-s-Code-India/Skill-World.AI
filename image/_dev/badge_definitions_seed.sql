-- SkillTube badge list (55 rows). Run once in Supabase SQL Editor AFTER the main setup.
-- The database keeps only the KEY. Pictures live in the repo folder image/ (see image/catalog.json).
create table if not exists public.badge_definitions (
  key text primary key,
  name text not null,
  tier text not null check (tier in ('gold','platinum','heroic','diamond','master')),
  field text not null,
  is_weekly boolean not null default false,
  active boolean not null default true
);
alter table public.badge_definitions enable row level security;
drop policy if exists "badge defs readable" on public.badge_definitions;
create policy "badge defs readable" on public.badge_definitions for select to authenticated using (true);
